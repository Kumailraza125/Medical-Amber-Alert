import {test,expect} from '@playwright/test';
test('Reject invalid actions and keep failed saves visible', async ({page,context}) => {
  await page.goto('/');
  await page.getByTestId('new-request').click();
  await page.getByTestId('send-request').click();
  await page.getByTestId('hospital-switch').selectOption('maple');
  await page.getByTestId('incoming-tab').click();
  await page.getByTestId('request-HC-1043').click();
  const second=await context.newPage();
  await second.goto('/');
  await second.getByTestId('hospital-switch').selectOption('maple');
  await second.getByTestId('incoming-tab').click();
  await second.getByTestId('request-HC-1043').click();
  await second.getByTestId('availability').fill('45');
  await second.getByTestId('offer-availability').click();
  await expect(second.getByTestId('offer-confirmation')).toBeVisible();
  await page.getByTestId('availability').fill('90');
  await page.getByTestId('offer-availability').click();
  await expect(page.locator('#toast')).toContainText('cannot offer again');
  await expect(page.getByTestId('offer-availability')).toBeVisible();
  await expect(page.getByTestId('save-error')).toContainText('Your change was not saved');
  await page.waitForTimeout(4500);
  await expect(page.getByTestId('save-error')).toBeVisible();
  const saved=await context.request.get('/api/requests');
  const r=(await saved.json()).requests.find((r:any)=>r.id==='HC-1043');
  const invalid=await context.request.post('/api/requests',{data:{hospitalId:'unknown',resource:'MRI',urgency:'Urgent',radiusKm:100,note:''}});
  expect(invalid.status()).toBe(400);
  const premature=await context.request.post(`/api/requests/${r.recordId}/complete`,{data:{hospitalId:'cedar'}});
  expect(premature.status()).toBe(409);
  const otherHospital=await context.request.post(`/api/requests/${r.recordId}/accept`,{data:{hospitalId:'north',acceptedHospitalId:'maple'}});
  expect(otherHospital.status()).toBe(403);
  await page.reload();
  await page.getByTestId('request-HC-1043').click();
  await expect(page.locator('#detail-modal')).toContainText('Available in 45 minutes');
  await expect(page.locator('#detail-modal')).not.toContainText('Available in 90 minutes');
  await expect(page.locator('#detail-modal .response-card')).toHaveCount(1);
  await expect(page.locator('#detail-modal')).toContainText('Awaiting responses');
});
